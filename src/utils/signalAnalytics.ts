export type OutcomeHorizon = 'm5' | 'm15' | 'h1' | 'h4'

export interface HorizonMetric {
  /** Signed close return at horizon end: (close - entry) / entry * 100. */
  ret: number
  /** Max favorable excursion (%) in the signal's direction during the window. */
  mfe: number
  /** Max adverse excursion (%) against the signal's direction (non-negative). */
  mae: number
}

export interface HorizonOutcomes {
  m5?: HorizonMetric
  m15?: HorizonMetric
  h1?: HorizonMetric
  h4?: HorizonMetric
}

export interface SignalSampleReason {
  kind: string
  label: string
  detail: string
  deviation?: number | null
}

export interface SignalSampleContext {
  kind: BackdropKind
  label: string
  detail: string
}

/**
 * A persisted record of one anomaly firing — either captured live from the
 * board (IndexedDB journal) or generated by the offline historical backtester.
 * Both sources share this shape so the in-app Signal Lab and CLI report run
 * identical analytics.
 */
export interface SignalSample {
  id: string
  instId: string
  at: number
  headline: string
  tier: FlagTier
  regime: SignalRegime | null
  direction: SignalDirection
  families: SignalFamily[]
  kinds: SignalKind[]
  backdropKinds: BackdropKind[]
  reasons: SignalSampleReason[]
  context?: SignalSampleContext[]
  triggerPrice: number
  source: 'live' | 'backtest'
  outcomes?: HorizonOutcomes
}

export const HORIZON_MS: Record<OutcomeHorizon, number> = {
  m5: 5 * 60 * 1000,
  m15: 15 * 60 * 1000,
  h1: 60 * 60 * 1000,
  h4: 4 * 60 * 60 * 1000,
}

export const ALL_HORIZONS: OutcomeHorizon[] = ['m5', 'm15', 'h1', 'h4']

const BAR_5M_MS = 5 * 60 * 1000

const round2 = (value: number) => Number(value.toFixed(2))

/**
 * Computes exact realized return, MFE, and MAE for every matured horizon using
 * closed 5-minute candles covering `[sample.at, sample.at + 4h]`.
 *
 * Strictly uses candles whose close time (`openTs + barMs`) is past `sample.at`
 * and whose open time is before `sample.at + horizonMs`, requiring the window's
 * end bar to be closed before stamping a horizon as final.
 */
export function computeOutcomesFromKlines(
  sample: Pick<SignalSample, 'at' | 'triggerPrice' | 'direction' | 'outcomes'>,
  klines: OkxKline[],
  now = Date.now(),
  barMs = BAR_5M_MS,
): HorizonOutcomes {
  const entry = sample.triggerPrice
  const existing = sample.outcomes ?? {}
  if (!(entry > 0) || !klines.length) return existing

  const closed = klines
    .filter((bar) => bar[8] === '1')
    .map((bar) => ({
      openTs: Number(bar[0]),
      closeTs: Number(bar[0]) + barMs,
      high: Number(bar[2]),
      low: Number(bar[3]),
      close: Number(bar[4]),
    }))
    .filter(
      (bar) =>
        Number.isFinite(bar.openTs) &&
        bar.high > 0 &&
        bar.low > 0 &&
        bar.close > 0,
    )
    .sort((a, b) => a.openTs - b.openTs)

  if (!closed.length) return existing

  const next: HorizonOutcomes = { ...existing }

  for (const horizon of ALL_HORIZONS) {
    if (next[horizon]) continue
    const endTs = sample.at + HORIZON_MS[horizon]
    if (now < endTs) continue

    // Bars overlapping (sample.at, endTs], plus the bar that straddles endTs.
    const windowBars = closed.filter(
      (bar) => bar.closeTs > sample.at && bar.openTs < endTs,
    )
    if (!windowBars.length) continue

    const lastBar = windowBars[windowBars.length - 1]
    // Ensure we actually have candle coverage through the horizon endpoint.
    if (lastBar.closeTs < endTs) continue

    let maxHigh = -Infinity
    let minLow = Infinity
    for (const bar of windowBars) {
      if (bar.high > maxHigh) maxHigh = bar.high
      if (bar.low < minLow) minLow = bar.low
    }

    const ret = ((lastBar.close - entry) / entry) * 100
    const maxUp = Math.max(0, ((maxHigh - entry) / entry) * 100)
    const maxDown = Math.max(0, ((entry - minLow) / entry) * 100)

    const isDown = sample.direction === 'down'
    const mfe = isDown ? maxDown : maxUp
    const mae = isDown ? maxUp : maxDown

    next[horizon] = {
      ret: round2(ret),
      mfe: round2(mfe),
      mae: round2(mae),
    }
  }

  return next
}

export function directionalReturnOf(
  metric: HorizonMetric,
  direction: SignalDirection,
) {
  return direction === 'down' ? -metric.ret : metric.ret
}

export interface GroupStats {
  total: number
  evaluated: number
  directionalCount: number
  /** Percentage (0-100) of directional samples continuing in signal direction. */
  continuationRate: number | null
  /** Percentage (0-100) reversing against signal direction. */
  reversionRate: number | null
  /** Mean signed return aligned with signal direction (%). */
  avgDirectionalRet: number | null
  /** Median signed return aligned with signal direction (%). */
  medianDirectionalRet: number | null
  /** Mean absolute price excursion at horizon close (%). */
  avgAbsMove: number | null
  /** Mean max favorable excursion (%). */
  avgMfe: number | null
  /** Mean max adverse excursion (%). */
  avgMae: number | null
  /** Ratio of mean MFE to mean MAE (reward/risk excursion ratio). */
  mfeMaeRatio: number | null
}

export function aggregateSamples(
  samples: SignalSample[],
  horizon: OutcomeHorizon,
): GroupStats {
  const total = samples.length
  const evaluatedSamples = samples.filter(
    (sample) => sample.outcomes?.[horizon] !== undefined,
  )
  const evaluated = evaluatedSamples.length

  if (!evaluated) {
    return {
      total,
      evaluated: 0,
      directionalCount: 0,
      continuationRate: null,
      reversionRate: null,
      avgDirectionalRet: null,
      medianDirectionalRet: null,
      avgAbsMove: null,
      avgMfe: null,
      avgMae: null,
      mfeMaeRatio: null,
    }
  }

  const absMoves: number[] = []
  const mfes: number[] = []
  const maes: number[] = []
  const dirReturns: number[] = []

  for (const sample of evaluatedSamples) {
    const metric = sample.outcomes![horizon]!
    absMoves.push(Math.abs(metric.ret))
    mfes.push(metric.mfe)
    maes.push(metric.mae)
    if (sample.direction !== 'neutral') {
      dirReturns.push(directionalReturnOf(metric, sample.direction))
    }
  }

  const mean = (values: number[]) =>
    values.reduce((sum, value) => sum + value, 0) / values.length

  const avgAbsMove = round2(mean(absMoves))
  const avgMfe = round2(mean(mfes))
  const avgMae = round2(mean(maes))
  const mfeMaeRatio = avgMae > 0 ? round2(avgMfe / avgMae) : null

  const directionalCount = dirReturns.length
  if (!directionalCount) {
    return {
      total,
      evaluated,
      directionalCount: 0,
      continuationRate: null,
      reversionRate: null,
      avgDirectionalRet: null,
      medianDirectionalRet: null,
      avgAbsMove,
      avgMfe,
      avgMae,
      mfeMaeRatio,
    }
  }

  const hits = dirReturns.filter((value) => value > 0).length
  const continuationRate = round2((hits / directionalCount) * 100)
  const reversionRate = round2(100 - continuationRate)
  const avgDirectionalRet = round2(mean(dirReturns))
  const med = medianOf(dirReturns)

  return {
    total,
    evaluated,
    directionalCount,
    continuationRate,
    reversionRate,
    avgDirectionalRet,
    medianDirectionalRet: med === null ? null : round2(med),
    avgAbsMove,
    avgMfe,
    avgMae,
    mfeMaeRatio,
  }
}

export type TradingSession = 'asia' | 'europe' | 'us'

/** Classifies a UTC timestamp into the three primary global liquidity sessions. */
export function sessionOfTimestamp(ts: number): TradingSession {
  const hour = new Date(ts).getUTCHours()
  if (hour < 8) return 'asia'
  if (hour < 16) return 'europe'
  return 'us'
}

export interface BreakdownRow<K extends string = string> {
  key: K
  stats: GroupStats
}

export interface ReturnBucket {
  label: string
  min: number
  max: number
  count: number
}

export interface AnalyticsReport {
  horizon: OutcomeHorizon
  spanDays: number
  alertsPerDay: number | null
  overall: GroupStats
  byTier: {
    high: GroupStats
    standard: GroupStats
  }
  byRegime: BreakdownRow<SignalRegime | 'other'>[]
  byKind: BreakdownRow<SignalKind>[]
  byBackdrop: BreakdownRow<BackdropKind | 'none'>[]
  bySession: BreakdownRow<TradingSession>[]
  bySymbol: BreakdownRow<string>[]
  distribution: ReturnBucket[]
}

const BUCKET_BOUNDS = [
  { label: '<-3%', min: -Infinity, max: -3 },
  { label: '-3~-1.5%', min: -3, max: -1.5 },
  { label: '-1.5~-0.5%', min: -1.5, max: -0.5 },
  { label: '-0.5~0%', min: -0.5, max: 0 },
  { label: '0~+0.5%', min: 0, max: 0.5 },
  { label: '+0.5~+1.5%', min: 0.5, max: 1.5 },
  { label: '+1.5~+3%', min: 1.5, max: 3 },
  { label: '>+3%', min: 3, max: Infinity },
]

function buildBuckets(
  samples: SignalSample[],
  horizon: OutcomeHorizon,
): ReturnBucket[] {
  const buckets = BUCKET_BOUNDS.map((b) => ({ ...b, count: 0 }))
  for (const sample of samples) {
    const metric = sample.outcomes?.[horizon]
    if (!metric || sample.direction === 'neutral') continue
    const val = directionalReturnOf(metric, sample.direction)
    const target = buckets.find(
      (bucket) => val >= bucket.min && val < bucket.max,
    )
    if (target) target.count++
  }
  return buckets
}

function groupAndAggregate<K extends string>(
  samples: SignalSample[],
  horizon: OutcomeHorizon,
  keysOf: (sample: SignalSample) => K[],
): BreakdownRow<K>[] {
  const map = new Map<K, SignalSample[]>()
  for (const sample of samples) {
    for (const key of keysOf(sample)) {
      const bucket = map.get(key)
      if (bucket) bucket.push(sample)
      else map.set(key, [sample])
    }
  }
  return [...map.entries()]
    .map(([key, items]) => ({
      key,
      stats: aggregateSamples(items, horizon),
    }))
    .sort((a, b) => b.stats.total - a.stats.total)
}

export function buildAnalyticsReport(
  samples: SignalSample[],
  horizon: OutcomeHorizon,
): AnalyticsReport {
  let minTs = Infinity
  let maxTs = -Infinity
  for (const sample of samples) {
    if (sample.at < minTs) minTs = sample.at
    if (sample.at > maxTs) maxTs = sample.at
  }
  const spanDays =
    samples.length >= 2 && maxTs > minTs
      ? Math.max((maxTs - minTs) / (24 * 60 * 60 * 1000), 1 / 24)
      : samples.length === 1
        ? 1
        : 0

  return {
    horizon,
    spanDays: round2(spanDays),
    alertsPerDay: spanDays > 0 ? round2(samples.length / spanDays) : null,
    overall: aggregateSamples(samples, horizon),
    byTier: {
      high: aggregateSamples(
        samples.filter((sample) => sample.tier === 'high'),
        horizon,
      ),
      standard: aggregateSamples(
        samples.filter((sample) => sample.tier === 'standard'),
        horizon,
      ),
    },
    byRegime: groupAndAggregate(samples, horizon, (sample) => [
      sample.regime ?? 'other',
    ]),
    byKind: groupAndAggregate(samples, horizon, (sample) => sample.kinds),
    byBackdrop: groupAndAggregate(samples, horizon, (sample) =>
      sample.backdropKinds.length ? sample.backdropKinds : ['none'],
    ),
    bySession: groupAndAggregate(samples, horizon, (sample) => [
      sessionOfTimestamp(sample.at),
    ]),
    bySymbol: groupAndAggregate(samples, horizon, (sample) => [sample.instId]),
    distribution: buildBuckets(samples, horizon),
  }
}

function escapeCsv(value: unknown) {
  const str = value === null || value === undefined ? '' : String(value)
  if (/[",\n]/.test(str)) return `"${str.replace(/"/g, '""')}"`
  return str
}

export function samplesToCsv(samples: SignalSample[]) {
  const headers = [
    'id',
    'time_utc',
    'instId',
    'source',
    'tier',
    'regime',
    'direction',
    'headline',
    'kinds',
    'backdrop',
    'triggerPrice',
    'm5_ret',
    'm5_mfe',
    'm5_mae',
    'm15_ret',
    'm15_mfe',
    'm15_mae',
    'h1_ret',
    'h1_mfe',
    'h1_mae',
    'h4_ret',
    'h4_mfe',
    'h4_mae',
  ]
  const rows = samples.map((s) =>
    [
      s.id,
      new Date(s.at).toISOString(),
      s.instId,
      s.source,
      s.tier,
      s.regime ?? '',
      s.direction,
      s.headline,
      s.kinds.join('|'),
      s.backdropKinds.join('|'),
      s.triggerPrice,
      s.outcomes?.m5?.ret ?? '',
      s.outcomes?.m5?.mfe ?? '',
      s.outcomes?.m5?.mae ?? '',
      s.outcomes?.m15?.ret ?? '',
      s.outcomes?.m15?.mfe ?? '',
      s.outcomes?.m15?.mae ?? '',
      s.outcomes?.h1?.ret ?? '',
      s.outcomes?.h1?.mfe ?? '',
      s.outcomes?.h1?.mae ?? '',
      s.outcomes?.h4?.ret ?? '',
      s.outcomes?.h4?.mfe ?? '',
      s.outcomes?.h4?.mae ?? '',
    ]
      .map(escapeCsv)
      .join(','),
  )
  return [headers.join(','), ...rows].join('\n')
}
